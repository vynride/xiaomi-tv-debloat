# Apply a profile, after snapshotting the current state and generating an undo script.
#
#   TV_HOST=192.168.1.50 ./scripts/apply.sh profiles/xiaomi-mitv-android9
#
# A profile directory may contain any of:
#   disable.txt        packages to disable with `pm disable-user` (reversible, nothing is uninstalled)
#   no-background.txt  packages to deny RUN_IN_BACKGROUND (app still works when opened)
#   settings.txt       `key=value` lines for `settings put global`
#
# Every run writes backups/<timestamp>/undo.sh that restores exactly what this run changed.
set -eu
. "$(dirname "$0")/common.sh"

PROFILE=${1:?usage: apply.sh <profile-dir>}
[ -d "$PROFILE" ] || { echo "no such profile: $PROFILE" >&2; exit 1; }
require_device

STAMP=$(date +%Y%m%d-%H%M%S)
OUT="backups/$STAMP"
mkdir -p "$OUT"
UNDO="$OUT/undo.sh"

# --- snapshot -------------------------------------------------------------
sh_ pm list packages    | sed 's/package://' | sort > "$OUT/packages-all.txt"
sh_ pm list packages -d | sed 's/package://' | sort > "$OUT/packages-disabled.txt"
sh_ settings list global > "$OUT/settings-global.txt"
sh_ cmd package resolve-activity --brief -a android.intent.action.MAIN \
    -c android.intent.category.HOME | tail -1 > "$OUT/home.txt"
echo "snapshot saved to $OUT/"

cat > "$UNDO" <<EOF
#!/bin/sh
# Generated by apply.sh on $STAMP for profile $PROFILE. Restores the pre-run state.
set -u
export ANDROID_SERIAL=\${ANDROID_SERIAL:-$ANDROID_SERIAL}
EOF
chmod +x "$UNDO"

# --- 1. disable packages --------------------------------------------------
if [ -f "$PROFILE/disable.txt" ]; then
  echo; echo "== Disabling packages"
  for p in $(read_list "$PROFILE/disable.txt"); do
    if ! grep -qx "$p" "$OUT/packages-all.txt"; then
      echo "skip (not installed): $p"; continue
    fi
    if grep -qx "$p" "$OUT/packages-disabled.txt"; then
      echo "skip (already disabled): $p"; continue
    fi
    printf '%s: ' "$p"; sh_ pm disable-user --user 0 "$p"
    echo "adb shell pm enable $p" >> "$UNDO"
  done
fi

# --- 2. deny background execution ----------------------------------------
if [ -f "$PROFILE/no-background.txt" ]; then
  echo; echo "== Restricting background execution"
  for p in $(read_list "$PROFILE/no-background.txt"); do
    if ! grep -qx "$p" "$OUT/packages-all.txt"; then
      echo "skip (not installed): $p"; continue
    fi
    prev=$(sh_ cmd appops get "$p" RUN_IN_BACKGROUND | sed -n 's/^RUN_IN_BACKGROUND: \([a-z]*\).*/\1/p')
    sh_ cmd appops set "$p" RUN_IN_BACKGROUND ignore
    echo "no-background: $p (was: ${prev:-default})"
    if [ -n "$prev" ]; then
      echo "adb shell cmd appops set $p RUN_IN_BACKGROUND $prev" >> "$UNDO"
    else
      echo "adb shell cmd appops set $p RUN_IN_BACKGROUND default" >> "$UNDO"
    fi
  done
  echo "adb shell cmd appops write-settings" >> "$UNDO"
fi

# --- 3. global settings ---------------------------------------------------
if [ -f "$PROFILE/settings.txt" ]; then
  echo; echo "== Settings"
  read_list "$PROFILE/settings.txt" | while IFS='=' read -r key val; do
    prev=$(sh_ settings get global "$key")
    sh_ settings put global "$key" "$val"
    echo "$key: $prev -> $val"
    if [ "$prev" = "null" ]; then
      echo "adb shell settings delete global $key" >> "$UNDO"
    else
      echo "adb shell settings put global $key $prev" >> "$UNDO"
    fi
  done
fi

echo 'echo "Restored. Reboot to finish: adb reboot"' >> "$UNDO"

flush_state
echo
echo "Done. Undo with: ./$UNDO"
echo "Reboot now (adb reboot) and run ./scripts/audit.sh to confirm the changes stuck."
